# Generates VO_RECORDING_LIST.md from the actual voice files + the question bank.
# Run:  powershell -NoProfile -ExecutionPolicy Bypass -File Tools\gen_vo_list.ps1
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$bank = Get-Content "$root\Assets\Resources\Data\levels.json" -Raw -Encoding UTF8 | ConvertFrom-Json

$map = [ordered]@{}
foreach ($lv in $bank.levels) {
    $map["vo_intro_lvl" + $lv.id + ".wav"] = "Level " + $lv.id + " intro: " + $lv.intro.story + " " + $lv.intro.goal
    foreach ($c in $lv.challenges) {
        $map[$c.vo + ".wav"] = $c.id + " prompt: " + $c.prompt
        $map["vo_fb_" + $c.id + "_ok.wav"]  = $c.id + " success: " + $c.feedback.success
        $map["vo_fb_" + $c.id + "_no.wav"]  = $c.id + " retry: " + $c.feedback.retry
        if ($c.media.voWord) { $map[$c.media.voWord + ".wav"] = "word pronunciation: " + $c.media.word.ToLower() }
        if ($c.media.voSentence) { $map[$c.media.voSentence + ".wav"] = "sentence: " + $c.media.sentence }
        if ($c.words) { foreach ($w in $c.words) { $map["vo_word_" + $w + ".wav"] = "word: " + $w } }
    }
}
$map["vo_story_intro.wav"] = "Onboarding story intro: Hello, young hero! Our magic crystal has been broken into twelve pieces. We need your help! Solve the challenges, collect the stars, and save our kingdom!"
foreach ($v in $bank.variants) {
    $map[$v.vo + ".wav"] = $v.id + " prompt: " + $v.prompt
    $map["vo_fb_" + $v.id + "_ok.wav"] = $v.id + " success: " + $v.feedback.success
    $map["vo_fb_" + $v.id + "_no.wav"] = $v.id + " retry: " + $v.feedback.retry
    if ($v.media.voWord -and $v.media.word) { $map[$v.media.voWord + ".wav"] = "word pronunciation: " + $v.media.word.ToLower() }
    if ($v.media.voSentence -and $v.media.sentence) { $map[$v.media.voSentence + ".wav"] = "sentence: " + $v.media.sentence }
    if ($v.words) { foreach ($w in $v.words) { $map["vo_word_" + $w + ".wav"] = "word: " + $w } }
}

# Batch 5 fix: the spoken number words (vo_word_one..vo_word_twenty) are generated
# by gen_vo.ps1 but were missing from this list — without them the list counted
# 281 rows while 299 WAV files exist on disk. Keep this table identical to the
# $numberWords table in gen_vo.ps1.
$numberWords = @{
    "vo_word_one"="one"; "vo_word_two"="two"; "vo_word_three"="three"; "vo_word_four"="four";
    "vo_word_five"="five"; "vo_word_six"="six"; "vo_word_seven"="seven"; "vo_word_eight"="eight";
    "vo_word_nine"="nine"; "vo_word_ten"="ten"; "vo_word_eleven"="eleven"; "vo_word_twelve"="twelve";
    "vo_word_thirteen"="thirteen"; "vo_word_fourteen"="fourteen"; "vo_word_fifteen"="fifteen";
    "vo_word_sixteen"="sixteen"; "vo_word_seventeen"="seventeen"; "vo_word_eighteen"="eighteen";
    "vo_word_nineteen"="nineteen"; "vo_word_twenty"="twenty"
}
foreach ($k in $numberWords.Keys) { if (-not $map.Contains($k + ".wav")) { $map[$k + ".wav"] = "word: " + $numberWords[$k] } }

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("# VO RECORDING LIST - replace the TTS placeholders with human recordings")
[void]$sb.AppendLine()
[void]$sb.AppendLine("$($map.Count) clips live in Assets/Resources/Audio/Voice/ (WAV, 16 kHz mono).")
[void]$sb.AppendLine("**Replace each file 1:1 by filename (WAV or OGG) - zero code changes.**")
[void]$sb.AppendLine("Recording notes: friendly, conversational, slightly slow pace; Lumo speaks every line (§8.9).")
[void]$sb.AppendLine()
[void]$sb.AppendLine("| File | Script |")
[void]$sb.AppendLine("|---|---|")
foreach ($k in $map.Keys) {
    $script = ($map[$k] -replace "\|", "/")
    [void]$sb.AppendLine("| $k | $script |")
}
[void]$sb.AppendLine()
[void]$sb.AppendLine("_Generated by Tools/gen_vo_list.ps1 from levels.json - regenerate after content changes._")
[IO.File]::WriteAllText("$root\VO_RECORDING_LIST.md", $sb.ToString(), (New-Object System.Text.UTF8Encoding($true)))
Write-Output ("VO_RECORDING_LIST.md written with " + $map.Count + " entries")
